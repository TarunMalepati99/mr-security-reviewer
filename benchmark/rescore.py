"""Rebuild benchmark/RESULTS.md from the saved runs in benchmark/results/.

    python benchmark/rescore.py

Re-scores each saved run's per-case outcomes with the current scoring code (so every row
uses the same metric definitions and confidence-interval method), and runs Bandit locally
on exactly the same held-out cases for the baseline row. Needs no API key.
"""

from __future__ import annotations

import json
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
sys.path.insert(0, str(HERE))
import run_benchmark as rb  # noqa: E402

RUNS = [  # (label, saved run file prefix)
    ("Gemini, original prompt (v1)", "owasp-test_gemini-v1_"),
    ("Gemini, prompt v2", "owasp-test_gemini-v2_"),
    ("Gemini, prompt v2 + exploitability check", "owasp-test_gemini-v2-check_"),
]


def latest(prefix: str) -> Path | None:
    files = sorted((HERE / "results").glob(prefix + "*.json"))
    return files[-1] if files else None


def row(label: str, s: dict, model: str) -> str:
    lo, hi = s["benchmark_score_ci95"]
    fpr = s["FP"] / (s["FP"] + s["TN"]) if s["FP"] + s["TN"] else 0.0
    return (f"| {label} | {model} | **{s['benchmark_score']:+.2f}** ({lo:+.2f} to {hi:+.2f}) | "
            f"{s['recall']:.0%} | {fpr:.0%} | {s['precision']:.0%} | {s['f1']:.2f} |")


def main() -> None:
    lines = ["# Benchmark results", "",
             "Generated by `python benchmark/rescore.py` from the saved runs in `benchmark/results/`.", "",
             "## OWASP Benchmark for Python -- 136 held-out cases", "",
             "The `test` split in `owasp_python/split.json`: up to 5 real and 5 safe cases for each of 14 "
             "vulnerability types, never inspected while designing the prompt or the exploitability check.", "",
             "| Setup | Model | Benchmark score (95% CI) | Recall | False-positive rate | Precision | F1 |",
             "|---|---|---|---|---|---|---|"]
    test_cases = rb.load_owasp("all", 7, "test")
    states = rb.run_bandit(test_cases)
    bandit = rb.summarize_owasp([rb.score_owasp_case(c, states[c["id"]]) for c in test_cases])
    lines.append(row("Bandit (static analyzer baseline)", bandit, "--"))
    per_cat = None
    for label, prefix in RUNS:
        f = latest(prefix)
        if not f:
            lines.append(f"| {label} | -- | not run yet | | | | |")
            continue
        d = json.loads(f.read_text(encoding="utf-8"))
        s = rb.summarize_owasp(d["cases"])
        model = d["summary"]["model"].split(",")[0]
        lines.append(row(label, s, f"`{model}`"))
        per_cat = s
    lines += ["", "Benchmark score = true-positive rate minus false-positive rate, averaged over the 14 "
              "categories (OWASP's scoring). The interval is centered on the score with Agresti-Coull "
              "variance per rate. False-positive rate here is pooled over all safe cases.", ""]
    if per_cat:
        lines += ["### Per category (prompt v2 + exploitability check)", "",
                  "| Category | TP | FN | FP | TN | TPR | FPR |", "|---|---|---|---|---|---|---|"]
        for cat, p in per_cat["per_category"].items():
            lines.append(f"| {rb.OWASP_NAMES[cat]} | {p['TP']} | {p['FN']} | {p['FP']} | {p['TN']} | "
                         f"{p['tpr']:.0%} | {p['fpr']:.0%} |")
        lines.append("")

    lines += ["## Compliance suite -- 32 hand-labeled merge requests", "",
              "| Analyzer | Recall | Precision | F1 | Clean MRs wrongly flagged |", "|---|---|---|---|---|"]
    for label, prefix in [("Pattern-matching stub", "compliance_stub_"), ("Bandit", "compliance_bandit_"),
                          ("Gemini, prompt v2 + exploitability check", "compliance_gemini-v2-check_")]:
        f = latest(prefix)
        if f:
            s = json.loads(f.read_text(encoding="utf-8"))["summary"]
            lines.append(f"| {label} | {s['recall']:.0%} | {s['precision']:.0%} | {s['f1']:.2f} | "
                         f"{s['clean_mrs_false_alarm']}/{s['clean_cases']} |")
    lines.append("")
    (HERE / "RESULTS.md").write_text("\n".join(lines), encoding="utf-8")
    print("\n".join(lines))


if __name__ == "__main__":
    main()
